#!/usr/bin/env node
/**
 * validate-route-reachability.mjs — deterministic route reachability validator (P4).
 *
 * Crawls every sidebar entry's URL against the built site (or a dev server)
 * and fails on 4xx/5xx (or unresolvable routes). The docs site uses
 * routeBasePath '/' so a doc id like 'memory/overview' maps to '/memory/overview'.
 *
 * Mode A — built site (default, standalone CI): reads the routes from a build
 * manifest produced by the prebuild step, or enumerates docs/*.md ids and
 * checks the corresponding file exists under <buildDir> (default ./build).
 * This is deterministic and needs no server.
 *
 * Mode B — live server (dev/serve): pass --base http://localhost:3000 and the
 * validator HTTP-GETs each route and fails on 4xx/5xx.
 *
 * Routes are sourced from the sidebar definition (sidebars.ts) so pages the
 * sidebar references are the contract. Autogenerated dirs (api/, sdks/*,
 * v-secure) are expanded from the docs/ file tree.
 *
 * USAGE:
 *   node scripts/validate-route-reachability.mjs                  # Mode A, ./build
 *   node scripts/validate-route-reachability.mjs --base http://localhost:3000
 *   node scripts/validate-route-reachability.mjs --build <dir>
 *
 * EXIT: 0 if all sidebar routes are reachable; 1 otherwise.
 *
 * ESCAPE HATCH (audit §6.5): do NOT delete this validator. If a route is
 * intentionally not-yet-built, add it to docs/.validator-allowlists/routes.json
 * (urls[] with reason). As a last resort the docs CI gates it behind
 * `ignore-docs-validator`.
 */

import { readFileSync, existsSync, readdirSync, statSync } from 'fs';
import { join, dirname, resolve } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(__dirname, '..');
const DEFAULT_BUILD = join(REPO_ROOT, 'build');
const ALLOWLIST = join(REPO_ROOT, 'docs/.validator-allowlists/routes.json');

function arg(name) {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : null;
}
const BASE = arg('--base'); // http server base (Mode B)
const BUILD = resolve(arg('--build') || DEFAULT_BUILD);
// Docs tree to enumerate routes from (override for fixtures).
const DOCS_DIR = resolve(arg('--docs') || join(REPO_ROOT, 'docs'));
// Sidebar definition file (override for fixtures).
const SIDEBAR_FILE = resolve(arg('--sidebar') || join(REPO_ROOT, 'sidebars.ts'));

let allowlist = { urls: [], reason: '' };
if (existsSync(ALLOWLIST)) {
  allowlist = JSON.parse(readFileSync(ALLOWLIST, 'utf8'));
}
const allowedUrls = new Set((allowlist.urls || []).map((u) => u.url || u));

/** Enumerate doc ids from docs/ tree (id = path relative to docs/, no ext). */
function docIds() {
  const ids = [];
  function walk(dir) {
    for (const entry of readdirSync(dir)) {
      const p = join(dir, entry);
      const st = statSync(p);
      if (st.isDirectory()) {
        // skip special dirs that don't hold content pages
        if (entry === '.validator-allowlists') continue;
        walk(p);
      } else if (/\.(md|mdx)$/.test(entry)) {
        const rel = p.slice(DOCS_DIR.length + 1).replace(/\.(md|mdx)$/, '');
        // skip _category_.json-like helpers
        if (rel.startsWith('_')) continue;
        ids.push(rel);
      }
    }
  }
  walk(DOCS_DIR);
  return ids;
}

/** Extract explicit doc-id references from sidebars.ts. */
function sidebarDocIds() {
  if (!existsSync(SIDEBAR_FILE)) return new Set();
  const src = readFileSync(SIDEBAR_FILE, 'utf8');
  const ids = new Set();
  // Bare doc-id entries, e.g. 'mcp/overview' or "mcp/overview"
  for (const m of src.matchAll(/^\s*['"]([a-z][a-z0-9/_.-]*)['"],?\s*$/gm)) {
    ids.add(m[1]);
  }
  // Object-form doc refs, e.g. { type: 'doc', id: 'mcp/overview' }
  for (const m of src.matchAll(/\{[\s\S]*?\btype\s*:\s*['"]doc['"][\s\S]*?\bid\s*:\s*['"]([a-z][a-z0-9/_.-]*)['"][\s\S]*?\}/gm)) {
    ids.add(m[1]);
  }
  return ids;
}

const routes = new Set();
for (const id of docIds()) routes.add('/' + id);
// Add sidebar-referenced ids not present as files (drafts) so they are checked
// against the build manifest / server and surfaced if unreachable.
const sidebarIds = sidebarDocIds();
const extra = [...sidebarIds].filter((id) => ![...routes].includes('/' + id));
for (const id of extra) routes.add('/' + id);

async function checkHttp(route) {
  const controller = new AbortController();
  const t = setTimeout(() => controller.abort(), 8000);
  try {
    const res = await fetch(BASE + route, { redirect: 'follow', signal: controller.signal });
    return res.status;
  } catch {
    return 0;
  } finally {
    clearTimeout(t);
  }
}

function checkBuilt(route) {
  // route like /memory/overview -> build/memory/overview/index.html or build/memory/overview.html
  const candidates = [
    join(BUILD, route.replace(/^\//, ''), 'index.html'),
    join(BUILD, route.replace(/^\//, '') + '.html'),
  ];
  for (const c of candidates) if (existsSync(c)) return 200;
  return 404;
}

async function run() {
  const routeList = [...routes].sort();
  const failures = [];

  if (BASE) {
    // Mode B: live server
    for (const route of routeList) {
      if (allowedUrls.has(route)) { console.log(`OK  (allowlisted) ${route}`); continue; }
      const status = await checkHttp(route);
      const ok = status !== 0 && status < 400;
      console.log(`${ok ? 'OK ' : 'ERR'} ${String(status).padStart(3)} ${route}`);
      if (!ok) failures.push({ route, status });
    }
  } else {
    // Mode A: built site manifest
    if (!existsSync(BUILD)) {
      console.error(`❌ validate:route-reachability — build dir not found: ${BUILD}`);
      console.error('   Run `bun run build` first, or pass --base <url> for a live server.');
      process.exit(1);
    }
    for (const route of routeList) {
      if (allowedUrls.has(route)) { console.log(`OK  (allowlisted) ${route}`); continue; }
      const status = checkBuilt(route);
      const ok = status !== 0 && status < 400;
      console.log(`${ok ? 'OK ' : 'ERR'} ${String(status).padStart(3)} ${route}`);
      if (!ok) failures.push({ route, status });
    }
  }

  if (failures.length > 0) {
    console.error(`\n🔴 validate:route-reachability FAILED — ${failures.length} route(s) unreachable.`);
    for (const f of failures) console.error(`  ✗ ${f.route} (${f.status})`);
    console.error('   Add intentionally-not-yet-built routes to docs/.validator-allowlists/routes.json with a reason.');
    process.exit(1);
  } else {
    console.log(`✅ validate:route-reachability PASSED — ${routeList.length} sidebar route(s) reachable (mode: ${BASE ? 'live:' + BASE : 'build:' + BUILD}).`);
  }
}

run();
